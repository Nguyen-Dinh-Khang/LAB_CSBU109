// Swagger / OpenAPI 3.0 configuration 
const path = require('path');
const swaggerJSDoc = require('swagger-jsdoc'); 
const swaggerUi = require('swagger-ui-express'); 

// On Windows, glob requires forward slashes '/' instead of backslashes '\'
const routesPath = path.resolve(__dirname, '../routes/*.js').split(path.sep).join('/');
const modelsPath = path.resolve(__dirname, '../models/*.js').split(path.sep).join('/');
  
const options = { 
  definition: { 
    openapi: '3.0.0', 
    info: { 
      title: 'RESTful API Documentation - Web & Database Lab 3', 
      version: '1.0.0', 
      description: 'Interactive API documentation auto-generated by Swagger UI for Sales Management application' 
    }, 
    servers: [ 
      { 
        url: 'http://localhost:3000/api', 
        description: 'Development Local Server' 
      } 
    ],
    tags: [
      {
        name: 'Products',
        description: 'Endpoints for managing products'
      },
      {
        name: 'Categories',
        description: 'Endpoints for managing categories'
      }
    ],
    components: {
      parameters: {
        // Requirement 4: Reusable id path parameter under components.parameters
        id: {
          name: 'id',
          in: 'path',
          required: true,
          description: 'The 24-character hexadecimal MongoDB ObjectId of the resource',
          schema: {
            type: 'string',
            example: '671fe2a39b4d1c00234a5678'
          }
        }
      }
    }
  }, 
  // Files to scan for @swagger comments (normalized for cross-platform compatibility) 
  apis: [routesPath, modelsPath, './routes/*.js'] 
}; 
  
const swaggerSpec = swaggerJSDoc(options); 
  
const setupSwagger = (app) => { 
  app.use('/api-docs', swaggerUi.serve, swaggerUi.setup(swaggerSpec)); 
  console.log('Swagger UI documentation is ready at: http://localhost:3000/api-docs'); 
}; 
  
module.exports = setupSwagger;
